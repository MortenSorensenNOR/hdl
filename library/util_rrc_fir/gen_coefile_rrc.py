"""Generate coefile_rrc.coe for the FPGA RRC FIR filter.

Parameters match config.py: SPS=8, SPAN=8, RRC_ALPHA=0.35 → 129 taps.
Coefficients are scaled so the peak = 16384 (matching coefile_int.coe convention),
fitting in 16-bit signed integers with Data_Fractional_Bits=15.

Run this script from this directory to regenerate coefile_rrc.coe.
"""

import numpy as np

SPS = 4
SPAN = 8
ALPHA = 0.25
NUM_TAPS = 2 * SPS * SPAN + 1  # 65


def rrc_filter(sps: int, alpha: float, num_taps: int) -> np.ndarray:
    """Unit-energy RRC filter (same formula as modules/pulse_shaping.py)."""
    t = (np.arange(num_taps) - (num_taps - 1) / 2) / sps
    zero_mask = t == 0
    special_val = 1 / (4 * alpha)
    special_mask = np.abs(np.abs(t) - special_val) < 8 * np.finfo(np.float32).eps
    special_case = (
        alpha / np.sqrt(2)
        * ((1 + 2 / np.pi) * np.sin(np.pi / (4 * alpha))
           + (1 - 2 / np.pi) * np.cos(np.pi / (4 * alpha)))
    )
    general_mask = ~zero_mask & ~special_mask
    num = np.sin(np.pi * t * (1 - alpha)) + 4 * alpha * t * np.cos(np.pi * t * (1 + alpha))
    den = np.pi * t * (1 - (4 * alpha * t) ** 2)
    with np.errstate(divide="ignore", invalid="ignore"):
        general_vals = num / den

    h = np.select(
        [zero_mask, special_mask, general_mask],
        [1 + alpha * (4 / np.pi - 1), special_case, general_vals],
    )
    return (h / np.sqrt(np.sum(h ** 2))).astype(np.float64)


def main() -> None:
    h = rrc_filter(SPS, ALPHA, NUM_TAPS)

    # Scale so peak coefficient = 16384 (= 2^14), matching coefile_int.coe convention.
    # With Coefficient_Width=16 and Data_Fractional_Bits=15, the filter gain at DC is
    # sum(h_int) / 2^15. For RRC this is not unity (RRC ≠ lowpass), which is expected;
    # the matched-filter gain is sum(h^2) * scale^2 / 2^15.
    scale = 16384.0 / np.max(np.abs(h))
    h_int = np.round(h * scale).astype(np.int32)

    print(f"Taps: {NUM_TAPS}, scale: {scale:.1f}, "
          f"peak: {np.max(np.abs(h_int))}, symmetric: {np.allclose(h_int, h_int[::-1])}")

    lines = [
        "; FPGA RRC FIR filter coefficient (.COE) file",
        f"; SPS={SPS}, SPAN={SPAN}, alpha={ALPHA}, taps={NUM_TAPS}",
        "; Generated by gen_coefile_rrc.py",
        "Radix = 10;",
        "Coefficient_Width = 16;",
        "CoefData =",
    ]
    for i, v in enumerate(h_int):
        sep = "," if i < NUM_TAPS - 1 else ";"
        lines.append(f"  {int(v):6d}{sep}")

    out = "\n".join(lines) + "\n"
    with open("coefile_rrc.coe", "w") as f:
        f.write(out)
    print("Written coefile_rrc.coe")


if __name__ == "__main__":
    main()
